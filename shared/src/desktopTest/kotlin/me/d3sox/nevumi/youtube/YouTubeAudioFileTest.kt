package me.d3sox.nevumi.youtube

import kotlinx.coroutines.runBlocking
import me.d3sox.nevumi.soundcloud.ScGateTags
import org.jaudiotagger.audio.AudioFileIO
import org.jaudiotagger.tag.FieldKey
import java.io.File
import java.nio.ByteBuffer
import java.nio.file.Files
import java.nio.file.Path
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertTrue

class YouTubeAudioFileTest {
    private val assets = Path.of(System.getProperty("nevumi.testRoot"), "androidApp/src/androidTest/assets")

    private fun topLevelBoxes(file: File): List<String> {
        val bytes = ByteBuffer.wrap(file.readBytes())
        val types = mutableListOf<String>()
        while (bytes.remaining() >= 8) {
            val start = bytes.position()
            val size = bytes.int
            types += ByteArray(4).also(bytes::get).decodeToString()
            bytes.position(start + size)
        }
        return types
    }

    private fun mdatPayloads(file: File): ByteArray {
        val bytes = file.readBytes()
        val payloads = java.io.ByteArrayOutputStream()
        var position = 0
        while (position + 8 <= bytes.size) {
            val size = ByteBuffer.wrap(bytes, position, 4).int
            if (bytes.decodeToString(position + 4, position + 8) == "mdat") payloads.write(bytes, position + 8, size - 8)
            position += size
        }
        return payloads.toByteArray()
    }

    @Test fun aFragmentedDownloadBecomesAPlainTaggedM4aWithTheSameAudio() = runBlocking {
        val directory = Files.createTempDirectory("youtube-audio")
        try {
            // Built like YouTube's audio: an empty sample table, a segment index and moof/mdat fragments.
            val source = assets.resolve("youtube-fragmented.m4a").toFile()
            assertTrue(topLevelBoxes(source).count { it == "moof" } > 1)
            val target = directory.resolve("song.m4a").toFile()
            val cover = Files.readAllBytes(assets.resolve("cover.png"))
            finishYouTubeAudio(source.path, target.path, ScGateTags("One More Time", "Daft Punk", "Discovery", "House"), 2001, cover)

            assertEquals(listOf("ftyp", "moov", "mdat"), topLevelBoxes(target))
            val audio = AudioFileIO.read(target)
            assertEquals(3, audio.audioHeader.trackLength)
            val tag = audio.tag
            assertEquals("One More Time", tag.getFirst(FieldKey.TITLE))
            assertEquals("Daft Punk", tag.getFirst(FieldKey.ARTIST))
            assertEquals("Discovery", tag.getFirst(FieldKey.ALBUM))
            assertEquals("House", tag.getFirst(FieldKey.GENRE))
            assertEquals("2001", tag.getFirst(FieldKey.YEAR))
            assertNotNull(tag.firstArtwork)
            // The audio is copied unchanged: the mdat payloads of the fragments, in order, are the plain file's one mdat.
            assertTrue(mdatPayloads(source).contentEquals(mdatPayloads(target)))
        } finally { directory.toFile().deleteRecursively() }
    }

    @Test fun youTubeMusicDescriptionsNameTheAlbumAndYear() {
        val description = NewPipeYouTube.plainText("Provided to YouTube by Label<br><br>One More Time · Daft Punk<br><br>Discovery<br><br>" +
            "℗ 2001 Daft Life Limited<br><br>Released on: 2001-03-07<br><br>Auto-generated by YouTube.")
        assertEquals(YouTubeDetails("Discovery", 2001), NewPipeYouTube.details(description))
        assertEquals(YouTubeDetails(), NewPipeYouTube.details("Official video for One More Time"))
        // A single has no album paragraph of its own before the label line.
        assertEquals(YouTubeDetails("", 2001), NewPipeYouTube.details("Provided to YouTube by Label\n\nSong · Artist\n\n℗ 2001 Label"))
    }

    @Test fun uploadedVideosNamedArtistDashTitleSuggestThoseTags() {
        assertEquals("One More Time (Official Video)" to "Daft Punk",
            YouTubeTrack("a", "Daft Punk - One More Time (Official Video)", "DaftPunkVEVO").suggestedTags())
        assertEquals("One More Time" to "Daft Punk", YouTubeTrack("a", "One More Time", "Daft Punk", song = true).suggestedTags())
        assertEquals("Live in Paris" to "Some Channel", YouTubeTrack("a", "Live in Paris", "Some Channel").suggestedTags())
        assertEquals("Daft Punk - One More Time.m4a", youTubeFileName(ScGateTags("One More Time", "Daft Punk"), artistTitle = true))
        assertEquals("ACDC.m4a", youTubeFileName(ScGateTags("AC/DC", ""), artistTitle = false))
    }
}
